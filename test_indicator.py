"""Тестирование индикатора «много/средне/мало»."""
from catalog import _indicator


def test_indicator():
    """Прогон тестов для индикатора (с защитой от плохих данных)."""
    test_cases = [
        # ===== Корректные значения =====
        (21, "много", "21 > 20 (граница много)"),
        (25, "много", "25 > 20"),
        (20, "средне", "20 ≤ 20 (граница средне)"),
        (15, "средне", "15 в диапазоне 6–20"),
        (6,  "средне", "6 > 5 (граница средне)"),
        (5,  "мало",   "5 ≤ 5 (граница мало)"),
        (4,  "мало",   "4 ≤ 5"),
        (0,  "мало",   "0 ≤ 5 (минимум)"),
        (1000, "много",  "1000 — очень большое число"),
        (50,   "много",  "50 > 20"),
        (-1,   "мало",   "отрицательное → мало"),

        # ===== 3 новых теста (Задание 1 ДЗ) — плохие данные =====
        (None,  "мало", "None → мало (защита)"),
        ("10",  "средне", "строка '10' → 10 → средне"),
        (0.5,   "мало", "дробное 0.5 → 0 → мало"),

        # ===== Дополнительные проверки =====
        (20.9, "средне", "20.9 → 20 → средне"),
        ("abc", "мало", "невалидная строка → мало"),
        ("",    "мало", "пустая строка → мало"),
    ]

    print("=" * 70)
    print("ТЕСТИРОВАНИЕ ИНДИКАТОРА (с плохими данными)")
    print("=" * 70)

    passed = 0
    for qty, expected, comment in test_cases:
        try:
            result = _indicator(qty)
            status = "✅" if result == expected else "❌"
            if result == expected:
                passed += 1
            print(f"{status} qty={repr(qty):>6}: '{result}' "
                  f"(ожидалось '{expected}') — {comment}")
        except Exception as e:
            print(f"❌ qty={repr(qty)}: ИСКЛЮЧЕНИЕ — {e}")

    print("=" * 70)
    print(f"Пройдено: {passed} / {len(test_cases)}")

    return passed == len(test_cases)


if __name__ == "__main__":
    test_indicator()