"""Тестирование индикатора «много/средне/мало»."""
from catalog import _indicator


def test_indicator():
    """Прогон тестов для индикатора (3 уровня, без эмодзи)."""
    test_cases = [
        # ===== Базовые тесты =====
        (21, "много", "21 > 20 (граница много)"),
        (25, "много", "25 > 20"),
        (20, "средне", "20 ≤ 20 (граница средне)"),
        (15, "средне", "15 в диапазоне 6–20"),
        (6,  "средне", "6 > 5 (граница средне)"),
        (5,  "мало",   "5 ≤ 5 (граница мало)"),
        (4,  "мало",   "4 ≤ 5"),
        (0,  "мало",   "0 ≤ 5 (минимум)"),

        # ===== Ранее добавленные тесты =====
        (1000, "много",  "1000 — очень большое число"),
        (50,   "много",  "50 > 20"),
        (5,    "мало",   "5 — повторная граница (стабильность)"),
        (6,    "средне", "6 — повторная граница (стабильность)"),
        (-1,   "мало",   "отрицательное количество → мало"),

        # ===== 3 новых теста (Задание 4.6) =====
        (100, "много", "большое число"),
        (1,   "мало",  "минимальное > 0"),
        (-1,  "мало",  "отрицательное (крайний случай)"),
    ]

    print("=" * 70)
    print("ТЕСТИРОВАНИЕ ИНДИКАТОРА (3 уровня, без эмодзи)")
    print("=" * 70)

    passed = 0
    for qty, expected, comment in test_cases:
        result = _indicator(qty)
        status = "✅" if result == expected else "❌"
        if result == expected:
            passed += 1
        print(f"{status} qty={qty:>5}: '{result}' "
              f"(ожидалось '{expected}') — {comment}")

    print("=" * 70)
    print(f"Пройдено: {passed} / {len(test_cases)}")

    return passed == len(test_cases)


if __name__ == "__main__":
    test_indicator()