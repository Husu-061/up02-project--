"""Тестирование индикатора (3 уровня, без эмодзи в тексте)."""
from catalog import _indicator


def test_indicator():
    test_cases = [
        (21, "много", "21 > 20 (граница много)"),
        (25, "много", "25 > 20"),
        (20, "средне", "20 ≤ 20 (граница средне)"),
        (15, "средне", "15 в диапазоне 6–20"),
        (6, "средне", "6 > 5 (граница средне)"),
        (5, "мало", "5 ≤ 5 (граница мало)"),
        (4, "мало", "4 ≤ 5"),
        (1, "мало", "1 ≤ 5"),
        (0, "мало", "0 ≤ 5 (минимум)"),
        (1000, "много", "1000 — большое число"),
        (50, "много", "50 > 20"),
        (5, "мало", "5 — повторная граница"),
        (6, "средне", "6 — повторная граница"),
        (-1, "мало", "отрицательное количество"),
    ]

    print("=" * 70)
    print("ТЕСТИРОВАНИЕ ИНДИКАТОРА (без эмодзи в тексте)")
    print("=" * 70)

    passed = 0
    for qty, expected, comment in test_cases:
        result = _indicator(qty)
        status = "✅" if result == expected else "❌"
        if result == expected:
            passed += 1
        print(f"{status} qty={qty:>5}: '{result}' — {comment}")

    print("=" * 70)
    print(f"Пройдено: {passed} / {len(test_cases)}")


if __name__ == "__main__":
    test_indicator()