-- Задание 1. Самый дорогой товар
-- Условие: выведите название и цену самого дорогого товара.
-- Подсказка: ORDER BY цена DESC LIMIT 1.
-- Результат: Симфония №5 150.0
SELECT название, цена 
FROM Товар 
ORDER BY цена DESC 
LIMIT 1;

-- Задание 2. Самый дешёвый товар
-- Условие: выведите название и цену самого дешёвого товара.
-- Результат: Симфония №5 150.0
SELECT название, цена 
FROM Товар 
ORDER BY цена ASC 
LIMIT 1;

-- Задание 3. Товары одной категории
-- Условие: выведите название и цену товаров в категории «[ваша категория]».
-- Выбранная категория из Задания 6: Джаз
-- Результат: What a Wonderful World 90.0
SELECT название, цена 
FROM Товар 
WHERE жанр = 'Джаз';

-- Задание 4. Поиск по названию
-- Условие: найдите все товары, в названии которых есть буква «о».
-- Подсказка: WHERE название LIKE '%о%'.
