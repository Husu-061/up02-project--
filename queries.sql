-- Задание 5. Все заказы
-- Условие: выведите все заказы: id, дата, клиент, товар_id, количество.
-- Результат:
-- 1 2026-09-15 Иванов Иван Иванович 1 2
-- 2 2026-09-20 Петрова Анна Сергеевна 2 1
-- 3 2026-09-25 Иванов Иван Иванович 3 1
SELECT id, дата, клиент, товар_id, количество 
FROM Заказ;

-- Задание 6. Заказы конкретного клиента
-- Условие: выведите все заказы клиента «Иванов Иван Иванович».
-- Результат: 2 заказа
SELECT * 
FROM Заказ 
WHERE клиент = 'Иванов Иван Иванович';

-- Задание 7. JOIN — заказы с названиями товаров
-- Условие: выведите: дата, клиент, название товара, количество. 
-- Свяжите таблицы Заказ и Товар по товар_id.
-- Результат: основа для просмотра состава заказа в Задании 4 ДЭ.
SELECT Заказ.дата, Заказ.клиент, Товар.название, Заказ.количество 
FROM Заказ 
JOIN Товар ON Заказ.товар_id = Товар.id;
-- Результат (для справки):
-- 2026-09-15 Иванов Иван Иванович Hey Jude 2
-- 2026-09-20 Петрова Анна Сергеевна Billie Jean 1
-- 2026-09-25 Иванов Иван Иванович What a Wonderful World 1

-- Задание 8. Общая сумма всех заказов
-- Условие: посчитайте итоговую сумму всех заказов: Товар.цена × Заказ.количество.
-- Результат: 410 руб.
SELECT SUM(Товар.цена * Заказ.количество)
FROM Заказ
JOIN Товар ON Заказ.товар_id = Товар.id;

-- Задание 9. Количество заказов по клиентам
-- Условие: для каждого клиента посчитайте, сколько у него заказов.
-- Подсказка: GROUP BY клиент.
SELECT клиент, COUNT(*) 
FROM Заказ 
GROUP BY клиент;
-- Результат (для справки):
-- Иванов Иван Иванович 2
-- Петрова Анна Сергеевна 1

-- Задание 10. Свой запрос
-- Условие: придумайте свой запрос к БД. Опишите, что хотите получить, и напишите SQL.
-- Что я хочу получить: Вывести общую сумму заказов по каждому клиенту.
SELECT Заказ.клиент, SUM(Товар.цена * Заказ.количество) AS "Итого"
FROM Заказ
JOIN Товар ON Заказ.товар_id = Товар.id
GROUP BY Заказ.клиент;
